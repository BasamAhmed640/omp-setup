import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Obsidian evaluates main.js with its own require; sibling modules must be
// bundled. Commit the output so Git installs never need a build step.
const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  absWorkingDir: root, entryPoints: ['obsidian/plugin.cjs'],
  bundle: true, platform: 'browser', format: 'cjs', target: 'es2022',
  external: ['obsidian'], write: false,
  // Chart functions are serialized into an offline iframe. Keep their names.
  minify: false,
  banner: { js: '// Generated by npm run build. Edit obsidian/plugin.cjs and the shared .cjs modules.' },
});
const output = result.outputFiles[0].text;
const target = new URL('../obsidian/main.js', import.meta.url);
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')).replace(/\r\n/g, '\n') !== output) throw new Error('Companion bundle is stale. Run npm run build.');
} else await writeFile(target, output);
